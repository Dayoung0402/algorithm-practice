WITH RECURSIVE genertaion_CTE AS (
    
    SELECT ID, PARENT_ID, 1 AS GEN
    FROM ECOLI_DATA
    WHERE PARENT_ID IS NULL 
    
    UNION ALL 
    
    SELECT E.ID, E.PARENT_ID, G.GEN + 1
    FROM ECOLI_DATA AS E
    INNER JOIN genertaion_CTE AS G
    ON E.PARENT_ID = G.ID
    
)
SELECT COUNT(T1.ID) AS COUNT, T1.GEN AS GENERATION
FROM genertaion_CTE AS T1
LEFT JOIN ECOLI_DATA AS T2
ON T1.ID = T2.PARENT_ID
WHERE T2.PARENT_ID IS NULL
GROUP BY T1.GEN
ORDER BY T1.GEN;
